"""Fetch terminal-accessible training datasets into backend/data/.

Reads point coordinates from appeears_points.csv (generated by generate_points.py)
and downloads no-auth public API datasets:
  - NASA POWER daily weather (via existing nasa_power.fetch_live)
  - NASA POWER soil wetness & ET targets (GWETTOP, GWETROOT, GWETPROF, EVLAND)
  - Open-Meteo ERA5-Land daily soil moisture (0-7, 7-28, 28-100 cm) & ET0
  - ISRIC SoilGrids v2.0 soil properties (rest.isric.org)
  - USDA NRCS SSURGO soil survey data via Soil Data Access (SDA) REST API

Usage:
    python fetch_training_data.py --sources power_targets open_meteo --limit 5
    python fetch_training_data.py --sources power_targets open_meteo --start 2023-01-01 --end 2024-12-31
"""
from __future__ import annotations

import argparse
import csv
import json
import time
from datetime import date
from pathlib import Path
from typing import Dict, List

import requests

from nasa_power import POWER_URL, fetch_live as fetch_power_live

BASE_DIR = Path(__file__).resolve().parent
DATA_DIR = BASE_DIR / "data"

POWER_TARGET_PARAMS = "GWETTOP,GWETROOT,GWETPROF,EVLAND"
OPEN_METEO_URL = "https://archive-api.open-meteo.com/v1/archive"

SOILGRIDS_URL = "https://rest.isric.org/soilgrids/v2.0/properties/query"
SOILGRIDS_PROPS = ["bdod", "cec", "clay", "sand", "silt", "soc", "phh2o"]
SOILGRIDS_DEPTHS = ["0-5cm", "5-15cm", "15-30cm"]

SDA_URL = "https://sdmdataaccess.sc.egov.usda.gov/Tabular/post.rest"


def get_with_retry(
    url: str,
    params: dict,
    max_retries: int = 5,
    base_wait: float = 20.0,
) -> requests.Response:
    """GET with automatic backoff on HTTP 429 / transient 5xx responses."""
    for attempt in range(max_retries):
        r = requests.get(url, params=params, timeout=30)
        if r.status_code not in (429, 502, 503, 504):
            r.raise_for_status()
            return r
        retry_after = r.headers.get("Retry-After")
        wait = float(retry_after) if retry_after and retry_after.isdigit() else base_wait * (attempt + 1)
        print(f"  rate-limited ({r.status_code}); waiting {wait:.0f}s before retry {attempt + 1}/{max_retries}...")
        time.sleep(wait)
    r.raise_for_status()
    return r


def load_points(csv_path: Path, limit: int | None = None) -> List[Dict[str, str]]:
    with csv_path.open("r", newline="") as f:
        rows = list(csv.DictReader(f))
    return rows[:limit] if limit else rows


def fetch_nasa_power(points: List[Dict[str, str]], start: date, end: date, delay: float) -> None:
    out_dir = DATA_DIR / "nasa_power"
    out_dir.mkdir(parents=True, exist_ok=True)
    for pt in points:
        pid = pt["ID"]
        out_file = out_dir / f"{pid}.json"
        if out_file.exists():
            continue
        lat, lon = float(pt["Latitude"]), float(pt["Longitude"])
        try:
            rows = fetch_power_live(lat, lon, start, end)
            out_file.write_text(json.dumps({"id": pid, "lat": lat, "lon": lon, "daily": rows}, indent=2))
            print(f"[power] {pid}: saved {len(rows)} days")
        except Exception as exc:
            print(f"[power] {pid}: failed ({exc})")
        time.sleep(delay)


def fetch_power_targets(points: List[Dict[str, str]], start: date, end: date, delay: float) -> None:
    """Fetch NASA POWER soil wetness (GWETTOP/GWETROOT/GWETPROF) and EVLAND."""
    out_dir = DATA_DIR / "nasa_power_targets"
    out_dir.mkdir(parents=True, exist_ok=True)
    for pt in points:
        pid = pt["ID"]
        out_file = out_dir / f"{pid}.json"
        if out_file.exists():
            continue
        lat, lon = float(pt["Latitude"]), float(pt["Longitude"])
        try:
            r = get_with_retry(
                POWER_URL,
                params={
                    "parameters": POWER_TARGET_PARAMS,
                    "community": "AG",
                    "longitude": lon,
                    "latitude": lat,
                    "start": start.strftime("%Y%m%d"),
                    "end": end.strftime("%Y%m%d"),
                    "format": "JSON",
                },
            )
            p = r.json()["properties"]["parameter"]
            rows = []
            for k in sorted(p["GWETTOP"]):
                val = lambda name: p[name][k] if p[name][k] > -900 else None
                rows.append({
                    "date": f"{k[:4]}-{k[4:6]}-{k[6:]}",
                    "gwettop": val("GWETTOP"),
                    "gwetroot": val("GWETROOT"),
                    "gwetprof": val("GWETPROF"),
                    "evland": val("EVLAND"),
                })
            out_file.write_text(json.dumps({"id": pid, "lat": lat, "lon": lon, "daily": rows}, indent=2))
            print(f"[power_targets] {pid}: saved {len(rows)} days")
        except Exception as exc:
            print(f"[power_targets] {pid}: failed ({exc})")
        time.sleep(delay)


def fetch_open_meteo(points: List[Dict[str, str]], start: date, end: date, delay: float) -> None:
    """Fetch Open-Meteo ERA5-Land daily soil moisture (3 depths), soil temp, and ET0."""
    out_dir = DATA_DIR / "open_meteo"
    out_dir.mkdir(parents=True, exist_ok=True)
    hourly_vars = (
        "soil_moisture_0_to_7cm,soil_moisture_7_to_28cm,"
        "soil_moisture_28_to_100cm,soil_temperature_0_to_7cm"
    )
    for pt in points:
        pid = pt["ID"]
        out_file = out_dir / f"{pid}.json"
        if out_file.exists():
            continue
        lat, lon = float(pt["Latitude"]), float(pt["Longitude"])
        try:
            r = get_with_retry(
                OPEN_METEO_URL,
                params={
                    "latitude": lat,
                    "longitude": lon,
                    "start_date": start.isoformat(),
                    "end_date": end.isoformat(),
                    "hourly": hourly_vars,
                    "daily": "et0_fao_evapotranspiration",
                    "timezone": "UTC",
                },
            )
            payload = r.json()
            hourly = payload["hourly"]
            daily = payload["daily"]
            et0_by_day = dict(zip(daily["time"], daily["et0_fao_evapotranspiration"]))

            buckets: Dict[str, Dict[str, List[float]]] = {}
            for i, ts in enumerate(hourly["time"]):
                d = ts[:10]
                b = buckets.setdefault(d, {"sm_0_7": [], "sm_7_28": [], "sm_28_100": [], "st_0_7": []})
                for dst, src in [
                    ("sm_0_7", "soil_moisture_0_to_7cm"),
                    ("sm_7_28", "soil_moisture_7_to_28cm"),
                    ("sm_28_100", "soil_moisture_28_to_100cm"),
                    ("st_0_7", "soil_temperature_0_to_7cm"),
                ]:
                    v = hourly[src][i]
                    if v is not None:
                        b[dst].append(v)

            mean_or_none = lambda xs: round(sum(xs) / len(xs), 4) if xs else None
            rows = [
                {
                    "date": d,
                    "sm_0_7cm": mean_or_none(buckets[d]["sm_0_7"]),
                    "sm_7_28cm": mean_or_none(buckets[d]["sm_7_28"]),
                    "sm_28_100cm": mean_or_none(buckets[d]["sm_28_100"]),
                    "soil_temp_0_7cm": mean_or_none(buckets[d]["st_0_7"]),
                    "et0_mm": et0_by_day.get(d),
                }
                for d in sorted(buckets)
            ]
            out_file.write_text(json.dumps({"id": pid, "lat": lat, "lon": lon, "daily": rows}, indent=2))
            print(f"[open_meteo] {pid}: saved {len(rows)} days")
        except Exception as exc:
            print(f"[open_meteo] {pid}: failed ({exc})")
        time.sleep(delay)


def fetch_soilgrids(points: List[Dict[str, str]], delay: float) -> None:
    out_dir = DATA_DIR / "soilgrids"
    out_dir.mkdir(parents=True, exist_ok=True)
    for pt in points:
        pid = pt["ID"]
        out_file = out_dir / f"{pid}.json"
        if out_file.exists():
            continue
        lat, lon = float(pt["Latitude"]), float(pt["Longitude"])
        try:
            r = get_with_retry(
                SOILGRIDS_URL,
                params={
                    "lon": lon,
                    "lat": lat,
                    "property": SOILGRIDS_PROPS,
                    "depth": SOILGRIDS_DEPTHS,
                    "value": "mean",
                },
            )
            out_file.write_text(r.text)
            print(f"[soilgrids] {pid}: saved")
        except Exception as exc:
            print(f"[soilgrids] {pid}: failed ({exc})")
        time.sleep(delay)


def fetch_ssurgo(points: List[Dict[str, str]], delay: float) -> None:
    out_dir = DATA_DIR / "ssurgo"
    out_dir.mkdir(parents=True, exist_ok=True)
    for pt in points:
        pid = pt["ID"]
        out_file = out_dir / f"{pid}.json"
        if out_file.exists():
            continue
        lat, lon = float(pt["Latitude"]), float(pt["Longitude"])
        sql = f"""
        SELECT
            mu.mukey, mu.muname,
            c.cokey, c.compname, c.comppct_r, c.drainagecl, c.taxclname,
            ch.hzdept_r, ch.hzdepb_r, ch.awc_r, ch.claytotal_r, ch.sandtotal_r,
            ch.silttotal_r, ch.om_r, ch.ph1to1h2o_r, ch.dbthirdbar_r
        FROM mapunit AS mu
        INNER JOIN component AS c ON c.mukey = mu.mukey AND c.majcompflag = 'Yes'
        INNER JOIN chorizon AS ch ON ch.cokey = c.cokey
        WHERE mu.mukey IN (
            SELECT DISTINCT mukey
            FROM SDA_Get_Mukey_from_intersection_with_WktWgs84('point({lon} {lat})')
        )
        ORDER BY c.comppct_r DESC, ch.hzdept_r ASC
        """
        try:
            r = requests.post(
                SDA_URL,
                json={"query": sql, "format": "JSON+COLUMNNAME"},
                timeout=30,
            )
            r.raise_for_status()
            out_file.write_text(r.text)
            print(f"[ssurgo] {pid}: saved")
        except Exception as exc:
            print(f"[ssurgo] {pid}: failed ({exc})")
        time.sleep(delay)


def main() -> None:
    ap = argparse.ArgumentParser(description="Download public training data into backend/data/")
    ap.add_argument("--points", type=Path, default=BASE_DIR / "appeears_points.csv")
    ap.add_argument("--sources", nargs="+", default=["all"],
                    choices=["all", "power", "power_targets", "open_meteo", "soilgrids", "ssurgo"])
    ap.add_argument("--start", default="2023-01-01", help="YYYY-MM-DD for NASA POWER")
    ap.add_argument("--end", default="2024-12-31", help="YYYY-MM-DD for NASA POWER")
    ap.add_argument("--limit", type=int, default=None, help="Max points to fetch (for testing)")
    ap.add_argument("--delay", type=float, default=0.5, help="Seconds between requests")
    args = ap.parse_args()

    all_sources = {"power", "power_targets", "open_meteo", "soilgrids", "ssurgo"}
    sources = all_sources if "all" in args.sources else set(args.sources)
    points = load_points(args.points, args.limit)
    print(f"Loaded {len(points)} points from {args.points}")

    start_d = date.fromisoformat(args.start)
    end_d = date.fromisoformat(args.end)
    if "power" in sources:
        fetch_nasa_power(points, start_d, end_d, args.delay)
    if "power_targets" in sources:
        fetch_power_targets(points, start_d, end_d, args.delay)
    if "open_meteo" in sources:
        fetch_open_meteo(points, start_d, end_d, args.delay)
    if "soilgrids" in sources:
        fetch_soilgrids(points, args.delay)
    if "ssurgo" in sources:
        fetch_ssurgo(points, args.delay)


if __name__ == "__main__":
    main()
